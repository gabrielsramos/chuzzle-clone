using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;
using mgcore.Rendering;

namespace ChuzzleClone.GameScripts.Scenes;

public sealed class GameplayScene : IGameScene
{
    private readonly Grid _grid;
    public RenderEntity Root => _grid.GetGrid();

    public GameplayScene(GraphicsDevice graphicsDevice, Texture2D spriteSheet, Vector2 center)
    {
        _grid = new Grid(graphicsDevice, spriteSheet);
        _grid.Initialize(center);
        Root.DebugName = "Gameplay";
    }

    public void Update(GameTime gameTime) => _grid.Update(gameTime);

    public void ExplodeAllBalls() => _grid.ExplodeAllBalls();
    public void ExplodeMiddleRow() => _grid.ExplodeMiddleRow();
    public void ExplodeMiddleColumn() => _grid.ExplodeMiddleColumn();
    public void ResetGrid() => _grid.Reset();

    // The outline is generated by Grid; ball textures belong to ContentManager.
    public void Dispose() => Root.Texture?.Dispose();
}
